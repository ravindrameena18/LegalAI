    async def search_cases(self, query: str, filters: dict[str, Any] | None = None) -> list[CaseLawResponse]:
        q = (query or "").lower().strip()
        f = filters or {}
        court_filter = f.get("court_filter", "all")
        year_filter = f.get("year_filter", "all")
        sort_by = f.get("sort_by", "relevance")

        results: list[CaseLawResponse] = []
        retrieved_time = datetime.now(timezone.utc).strftime("%d/%m/%Y %H:%M UTC")

        for item in self.VERIFIED_BENCHMARK_CASES:
            # Court filter
            if court_filter != "all" and court_filter != "supreme_court":
                continue

            # Year filter
            if year_filter == "1_year" and item["year"] < 2023:
                continue
            elif year_filter == "3_years" and item["year"] < 2021:
                continue
            elif year_filter == "5_years" and item["year"] < 2019:
                continue

            # Match criteria
            if not q:
                results.append(CaseLawResponse(**item, retrieved_at=retrieved_time))
                continue

            tokens = q.split()
            title_lower = item["title"].lower()
            ratio_lower = item["ratio_decidendi"].lower()
            citation_lower = item["citation"].lower()
            section_lower = (item.get("relevant_section") or "").lower()
            summary_lower = item["summary"].lower()

            matched = False
            # Check full phrase or tokens
            if q in title_lower or q in citation_lower or q in section_lower or q in ratio_lower or q in summary_lower:
                matched = True
            elif any(t in title_lower or t in ratio_lower or t in section_lower or t in citation_lower for t in tokens if len(t) > 2):
                matched = True

            if matched:
                results.append(CaseLawResponse(**item, retrieved_at=retrieved_time))

        # Sorting
        if sort_by == "date_desc":
            results.sort(key=lambda x: x.year, reverse=True)
        elif sort_by == "date_asc":
            results.sort(key=lambda x: x.year)
        else:
            results.sort(key=lambda x: x.relevance_score, reverse=True)

        return results

